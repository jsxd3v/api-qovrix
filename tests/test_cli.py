import json

import respx
from typer.testing import CliRunner

from api_qovrix.cli.app import app
from api_qovrix.scaffold import json_schemas

runner = CliRunner()


def invoke(*args, cwd=None):
    import os

    old = os.getcwd()
    if cwd:
        os.chdir(cwd)
    try:
        return runner.invoke(app, list(args))
    finally:
        os.chdir(old)


@respx.mock
def test_init_validate_run_junit_json(tmp_path):
    respx.get("https://jsonplaceholder.typicode.com/todos/1").respond(200, json={"id": 1, "completed": False})
    respx.post("https://jsonplaceholder.typicode.com/posts").respond(201, json={"id": 101})
    respx.get("https://jsonplaceholder.typicode.com/posts/1/comments").respond(200, json=[{"email": "a@b.c"}])

    r = invoke("init", cwd=tmp_path)
    assert r.exit_code == 0, r.output
    assert (tmp_path / "api-qovrix.yaml").is_file()
    assert invoke("init", cwd=tmp_path).exit_code == 2  # refuses to overwrite

    r = invoke("validate", cwd=tmp_path)
    assert r.exit_code == 0 and "2 monitors in 1 services" in r.output

    r = invoke("run", "--junit", "out/junit.xml", "--json-out", "report.json", cwd=tmp_path)
    assert r.exit_code == 0, r.output
    assert "2 passed" in r.output
    report = json.loads((tmp_path / "report.json").read_text())
    assert report["ok"] is True and report["counts"]["pass"] == 2
    junit = (tmp_path / "out/junit.xml").read_text()
    assert '<testsuite name="example"' in junit and 'failures="0"' in junit

    r = invoke("run", "example-todo", "--update-baselines", cwd=tmp_path)
    assert r.exit_code == 0
    assert (tmp_path / ".api-qovrix/baselines/example-todo.json").is_file()
    r = invoke("drift", "show", "example-todo", cwd=tmp_path)
    assert r.exit_code == 0 and "$.completed" in r.output and "always" in r.output

    respx.get("https://jsonplaceholder.typicode.com/todos/1").respond(200, json={"id": "1"})
    r = invoke("run", "example-todo", cwd=tmp_path)
    assert r.exit_code == 1
    assert "DRIFT" in r.output and "$.completed" in r.output and "field removed" in r.output

    r = invoke("run", "--json-out", "-", "example-todo", cwd=tmp_path)
    assert json.loads(r.stdout)["monitors"][0]["steps"][0]["drift"]["status"] == "changed"


def test_run_unknown_monitor(tmp_path):
    invoke("init", cwd=tmp_path)
    r = invoke("run", "ghost", cwd=tmp_path)
    assert r.exit_code == 2 and "no monitor named 'ghost'" in r.output


def test_no_config():
    import tempfile

    with tempfile.TemporaryDirectory() as d:
        r = invoke("run", cwd=d)
    assert r.exit_code == 2 and "api-qovrix init" in r.output


def test_import_openapi(tmp_path):
    from tests.test_openapi import SPEC_30

    invoke("init", cwd=tmp_path)
    (tmp_path / "openapi.json").write_text(json.dumps(SPEC_30))
    r = invoke("import", "openapi", "openapi.json", cwd=tmp_path)
    assert r.exit_code == 0, r.output
    out = (tmp_path / "monitors/shop-api.yaml").read_text()
    assert "list-orders" in out and "Generated by api-qovrix" in out
    config = (tmp_path / "api-qovrix.yaml").read_text()
    assert "source: openapi.json" in config and "SHOP_API_TOKEN: ${env:SHOP_API_TOKEN}" in config
    assert "# Secrets always come from environment variables" in config  # comments preserved
    r = invoke("import", "openapi", "openapi.json", cwd=tmp_path)
    assert "no added or removed operations" in r.output
    assert invoke("validate", cwd=tmp_path).exit_code == 0


def test_version():
    r = invoke("--version")
    assert r.exit_code == 0 and r.output.startswith("api-qovrix ")


def test_published_schema_is_up_to_date():
    from pathlib import Path

    folder = Path(__file__).parent.parent / "schema"
    for name, schema in json_schemas().items():
        on_disk = json.loads((folder / name).read_text())
        assert on_disk == json.loads(json.dumps(schema)), (
            f"schema/{name} is stale: run 'api-qovrix schema --output schema'"
        )


def test_import_openapi_adds_secrets_section_and_reports_bad_config(tmp_path):
    from tests.test_openapi import SPEC_30

    (tmp_path / "openapi.json").write_text(json.dumps(SPEC_30))
    (tmp_path / "api-qovrix.yaml").write_text("version: 1\n")
    r = invoke("import", "openapi", "openapi.json", cwd=tmp_path)
    assert r.exit_code == 0, r.output
    config = (tmp_path / "api-qovrix.yaml").read_text()
    assert "secrets:" in config and "SHOP_API_TOKEN" in config

    (tmp_path / "api-qovrix.yaml").write_text("version: 1\nsecrets: [oops]\n")
    r = invoke("import", "openapi", "openapi.json", "--force", cwd=tmp_path)
    assert r.exit_code == 2 and "could not update" in r.output
