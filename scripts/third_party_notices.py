"""Write THIRD_PARTY_NOTICES.md: license texts of every runtime dependency.

The standalone binaries and the Docker image bundle these packages, and their licenses ask that the copyright
notices travel with redistributed copies. Run inside an environment where api-qovrix is installed:

    python scripts/third_party_notices.py > THIRD_PARTY_NOTICES.md
"""

from __future__ import annotations

import re
import sys
from importlib.metadata import Distribution, PackageNotFoundError, distribution

ROOT = "api-qovrix"
EXTRAS = {"httpx": {"http2"}}  # optional extras api-qovrix installs


def _name(requirement: str) -> str:
    return re.split(r"[ ;<>=!\[~(]", requirement, maxsplit=1)[0].lower().replace("_", "-")


def walk(name: str, seen: dict[str, Distribution]) -> None:
    key = name.lower().replace("_", "-")
    if key in seen:
        return
    try:
        dist = distribution(name)
    except PackageNotFoundError:
        return
    seen[key] = dist
    wanted = EXTRAS.get(key, set())
    for req in dist.requires or []:
        marker = req.split(";", 1)[1] if ";" in req else ""
        extra = re.search(r"extra\s*==\s*['\"]([^'\"]+)['\"]", marker)
        if extra and extra.group(1) not in wanted:
            continue
        if "python_version" in marker or "sys_platform" in marker or "platform_" in marker:
            continue  # environment-specific backports; not part of the 3.12+ build
        walk(_name(req), seen)


def license_texts(dist: Distribution) -> list[tuple[str, str]]:
    out = []
    for f in dist.files or []:
        upper = str(f).upper()
        if ("LICEN" in upper or "COPYING" in upper or upper.endswith("NOTICE")) and ".dist-info" in str(f):
            text = f.locate().read_text(encoding="utf-8", errors="replace")
            if text and text.strip():
                out.append((f.name, text.strip()))
    return out


def main() -> int:
    seen: dict[str, Distribution] = {}
    walk(ROOT, seen)
    seen.pop(ROOT, None)
    lines = [
        "# Third-party notices",
        "",
        "api-qovrix is licensed under Apache-2.0 (see LICENSE). The release binaries and the Docker image",
        "include the following open source packages, under their own licenses. Generated by",
        "`scripts/third_party_notices.py`.",
        "",
        "The standalone binaries are built with PyInstaller, whose bootloader is licensed under the GPL-2.0",
        "with an exception that allows distributing binaries built with it under any license.",
        "",
        "| Package | Version | License |",
        "|---|---|---|",
    ]
    for key in sorted(seen):
        d = seen[key]
        lic = d.metadata.get("License-Expression") or ""
        if not lic:
            classifiers = [c.split("::")[-1].strip() for c in d.metadata.get_all("Classifier") or []]
            lic = "; ".join(c for c in classifiers if "License" in c or "BSD" in c or "MIT" in c)
        if not lic:
            lic = (
                (d.metadata.get("License") or "").splitlines()[0][:60]
                if d.metadata.get("License")
                else "see text"
            )
        lines.append(f"| {d.metadata['Name']} | {d.version} | {lic} |")
    for key in sorted(seen):
        d = seen[key]
        lines += ["", f"## {d.metadata['Name']} {d.version}", ""]
        texts = license_texts(d)
        if not texts:
            lines.append(
                f"License: {d.metadata.get('License-Expression') or d.metadata.get('License') or 'unknown'}"
            )
        for fname, text in texts:
            lines += [f"`{fname}`", "", "```text", text, "```", ""]
    sys.stdout.write("\n".join(lines).rstrip() + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
